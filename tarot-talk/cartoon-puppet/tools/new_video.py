"""Start a new video in one command.

    python3 tools/new_video.py <slug>

Needs ../videos/<slug>/ with the script package: script.json (beats: id, type, start, end, who, line, caption_chunks,
picture, camera, sound), cast.json, voices/cue_sheet.csv (id, who, start_s, end_s, file) and voices/voice_track_timed.wav
(see ../videos/2027-warmup-mulank8/ for the exact shape).

It writes, without overwriting anything that exists:
  ../videos/<slug>/video.json     config: speakers, meme lines, sfx cue file, music plan, loudness
  ../videos/<slug>/captions.json  caption chunks from script.json
  ../videos/<slug>/sfx_cues.json  empty cue list to fill
  cuts/<slug>.js                  a shot list with one shot per beat, the right character talking in a default pose,
                                  and every beat's picture / camera / sound notes as comments to act on
and prints which characters already exist in the library and which ones need a new char_<id>.js.
"""
import json, os, sys, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
slug = sys.argv[1]; V = os.path.join(HERE, '..', 'videos', slug)
S = json.load(open(os.path.join(V, 'script.json'))); CAST = json.load(open(os.path.join(V, 'cast.json')))
LIB = {  # characters already drawn and approved (char_*.js + cast_*.js); key = kind used by kit.js / act.js
    'monty': 'Monty, comic lead (mp(i), 8 poses)', 'vishnu': 'Vishnu ji on his cloud (vp(i), 6 poses)', 'shani': 'Shani dev standing (sp(i), 9 poses)',
    'brahma': 'Brahma ji at the token counter (bp(i), 5 poses)', 'sakshi': 'Sakshi, cute modern girl host (kp(i), 5 poses)', 'bunty': 'bust (SD.bunty)', 'khanna': 'bust (SD.khanna)'}
def kind_of(name):
    n = name.lower()
    for k in LIB:
        if k in n: return k
    for c in CAST.get('characters', []):
        if c.get('name', '').lower() == n or c.get('id', '').lower() == n: return c['id'].lower()
    return re.sub(r'[^a-z]', '', n)
speakers = sorted({b['who'] for b in S['beats'] if b.get('who')})
spk_map = {w: kind_of(w) for w in speakers}
def write(p, text):
    if os.path.exists(p): print('kept   ', os.path.relpath(p, HERE)); return
    open(p, 'w').write(text); print('wrote  ', os.path.relpath(p, HERE))
dur = max(b['end'] for b in S['beats'])
write(os.path.join(V, 'video.json'), json.dumps({
    'slug': slug, 'title': S.get('meta', {}).get('title', slug), 'script_dur': dur, 'cut': f'cuts/{slug}.js',
    'voice_track': 'voices/voice_track_timed.wav', 'cue_sheet': 'voices/cue_sheet.csv', 'speakers': spk_map,
    'meme_lines': [], 'sound_files': {}, 'sfx_cues': 'sfx_cues.json',
    'music': [{'kind': 'groove', 'a': 0, 'b': dur, 'bpm': 108, 'root': 220, 'level': 0.85}], 'music_db': -13, 'duck_db': -8, 'lufs': -14}, indent=1, ensure_ascii=False))
caps = [[c['text'], c['from'], c['to']] for b in S['beats'] for c in b.get('caption_chunks', [])]
write(os.path.join(V, 'captions.json'), json.dumps(caps, ensure_ascii=False, indent=0))
write(os.path.join(V, 'sfx_cues.json'), json.dumps({'note': '[script time s, sound, gain dB, (in s), (out s)]: our sfx name, meme:<file>, or voice:<path>', 'cues': []}, indent=0))
# shot list skeleton
CALL = {'monty': "monty(mp(0), 540, 1120, 0.95, t)", 'vishnu': "vishnu(vp(0), 540, 1080, 0.9, t)", 'shani': "shani(sp(0), 540, 1000, 0.98, t)",
        'sakshi': "sakshi(kp(0), 540, 1150, 0.82, t)", 'brahma': "brahma(bp(0), t)"}
SCENE = {'brahma': 'officeScene', 'shani': 'courtScene'}
lines = []
for b in S['beats']:
    k = spk_map.get(b.get('who'), None); actor = CALL.get(k, f"'' /* TODO: no library character for {b.get('who') or 'this beat'} */")
    scene = SCENE.get(k, 'terraceScene')
    notes = ' | '.join(f"{f}: {b[f]}" for f in ('line', 'picture', 'camera', 'sound') if b.get(f)).replace('*/', '* /')
    lines.append(f"  // {b['id']} {b.get('who') or ''}  {notes}\n  [{b['start']}, {b['end']}, t => {scene}(t, {actor})],")
cut = f"""// Film: {S.get('meta', {}).get('title', slug)}. Generated by tools/new_video.py; now make each shot real:
// pick the location scene, poses (cast_*.js POSES index), placement/scale (keep prop_gate.js passing), camera (cam/focus),
// graphics (tag, pill, commentBox, rainCloud, bricks or your own), following each beat's picture/camera/sound notes.
const K = require('../kit');
const {{ E, L, M, SD, clamp, ease, backOut, vp, mp, bp, sp, kp, vishnu, monty, shani, brahma, sakshi, cam, focus, txt, tag, pill, rainCloud, commentBox, bricks, terraceScene, officeScene, courtScene }} = K;

const SHOTS = [
{chr(10).join(lines)}
];
module.exports = K.film(SHOTS, {dur});
"""
os.makedirs(os.path.join(HERE, 'cuts'), exist_ok=True); write(os.path.join(HERE, 'cuts', f'{slug}.js'), cut)
print('\nspeakers -> characters:')
for w, k in spk_map.items(): print(f'  {w:14s} -> {k:8s} ' + (f'in library: {LIB[k]}' if k in LIB else 'NEW: write char_%s.js + cast_%s.js (Batch 1), add a helper in kit.js and a kind in act.js' % (k, k)))
print(f'\nnext: bash make_reel.sh {slug}   (renders the skeleton on the real voice track; then refine shots batch by batch)')
